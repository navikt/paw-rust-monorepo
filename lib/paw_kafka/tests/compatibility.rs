fn leak<T>(val: T) -> &'static T {
    Box::leak(Box::new(val))
}

fn signer() -> RecordSigner {
    RecordSigner::from_pkcs8_base64("test-ecdsa-v1", PRIVATE_KEY).unwrap()
}
fn verifier() -> RecordVerifier {
    let mut verifier = RecordVerifier::new();
    let pub_key = leak(PublicKey::active("test-ecdsa-v1", PUBLIC_KEY).unwrap());
    verifier.add_key(pub_key).unwrap();
    verifier
}

