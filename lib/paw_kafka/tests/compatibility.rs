#[test]
fn java_signed_vector_is_valid_in_rust() {
    let headers = OwnedHeaders::new()
        .insert(Header {
            key: "traceparent",
            value: Some(TRACEPARENT),
        })
        .insert(Header {
            key: SIGNATURE_HEADER,
            value: Some(JVM_SIGNATURE),
        })
        .insert(Header {
            key: SIGNING_KEY_ID_HEADER,
            value: Some("test-ecdsa-v1"),
        });
    assert!(matches!(
        verifier().validate(reference_time(), &message(Some(headers))),
        Ok(ValidSignature {
            key_id: "test-ecdsa-v1"
        })
    ));
}

#[test]
fn revoked_key_is_valid_before_but_not_at_revocation_time() {
    let revoked_after = reference_time().to_rfc3339();
    let key = leak(
        PublicKey::revoked("test-ecdsa-v1", PUBLIC_KEY, &revoked_after, &revoked_after).unwrap(),
    );
    let mut verifier = RecordVerifier::new();
    verifier.add_key(key).unwrap();
    let headers = OwnedHeaders::new()
        .insert(Header {
            key: SIGNATURE_HEADER,
            value: Some(JVM_SIGNATURE),
        })
        .insert(Header {
            key: SIGNING_KEY_ID_HEADER,
            value: Some("test-ecdsa-v1"),
        })
        .insert(Header {
            key: "traceparent",
            value: Some(TRACEPARENT),
        });
    let record = message(Some(headers));
    assert!(matches!(
        verifier.validate(
            reference_time() - chrono::Duration::milliseconds(1),
            &record
        ),
        Ok(ValidSignature {
            key_id: "test-ecdsa-v1"
        })
    ));
    assert!(matches!(
        verifier.validate(reference_time(), &record),
        Err(VerificationError::Key(KeyError::KeyRevoked {
            key_id: "test-ecdsa-v1",
            ..
        }))
    ));
}

// This signature was produced by the Rust signer and verified by Java's
// SHA256withECDSA using the public key above and the same signed bytes.
const RUST_SIGNATURE: &str = "MEUCIQDzxaNPDMm1uutfOMxIkpNQpvCMdK0aJgh2TmvS9z8CBgIgQ3rbl1_x5KmTeNgaC5mK0XPckRDJrXFJQMlQFozGwrc";

#[test]
fn rust_signature_for_jvm_verification() {
    let signed = signer()
        .sign_record(
            FutureRecord::to("topic")
                .key("key")
                .payload("value")
                .timestamp(TIMESTAMP)
                .headers(OwnedHeaders::new().insert(Header {
                    key: "traceparent",
                    value: Some(TRACEPARENT),
                })),
        )
        .unwrap();
    let signature = signed.headers.unwrap();
    let signature = signature
        .iter()
        .find(|h| h.key == SIGNATURE_HEADER)
        .unwrap();
    let signature = std::str::from_utf8(signature.value.unwrap()).unwrap();
    assert_eq!(signature, RUST_SIGNATURE);
    assert!(!signature.contains(['=', '+', '/']));
}

