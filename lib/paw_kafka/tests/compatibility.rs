#[test]
fn sign_record_replaces_old_headers_and_validates_without_changing_message() {
    let headers = OwnedHeaders::new()
        .insert(Header {
            key: SIGNATURE_HEADER,
            value: Some("old"),
        })
        .insert(Header {
            key: "traceparent",
            value: Some("obsolete"),
        })
        .insert(Header {
            key: "traceparent",
            value: Some(TRACEPARENT),
        })
        .insert(Header {
            key: SIGNING_KEY_ID_HEADER,
            value: Some("old"),
        });
    let record = FutureRecord::to("topic")
        .key("key")
        .payload("value")
        .timestamp(TIMESTAMP)
        .headers(headers);
    let signed = signer().sign_record(record).unwrap();
    let timestamp = signed.timestamp.unwrap();
    let headers = signed.headers.unwrap();
    assert_eq!(
        headers.iter().filter(|h| h.key == SIGNATURE_HEADER).count(),
        1
    );
    assert_eq!(headers.iter().filter(|h| h.key == "traceparent").count(), 2);
    let record = OwnedMessage::new(
        Some(b"value".to_vec()),
        Some(b"key".to_vec()),
        "topic".into(),
        Timestamp::CreateTime(timestamp),
        2,
        42,
        Some(headers),
    );
    assert!(matches!(
        verifier().validate(reference_time(), &record),
        Ok(ValidSignature {
            key_id: "test-ecdsa-v1"
        })
    ));
    assert_eq!(record.payload(), Some(b"value".as_slice()));
    assert!(matches!(
        verifier().validate(
            reference_time(),
            &record.clone().set_payload(Some(b"tampered".to_vec()))
        ),
        Err(VerificationError::SignatureMismatch {
            key_id: "test-ecdsa-v1"
        })
    ));
    assert!(matches!(
        verifier().validate(
            reference_time(),
            &record.clone().set_key(Some(b"tampered".to_vec()))
        ),
        Err(VerificationError::SignatureMismatch {
            key_id: "test-ecdsa-v1"
        })
    ));
    assert!(matches!(
        verifier().validate(
            reference_time(),
            &record.set_timestamp(Timestamp::CreateTime(timestamp + 1))
        ),
        Err(VerificationError::SignatureMismatch {
            key_id: "test-ecdsa-v1"
        })
    ));
}

#[test]
fn missing_or_bad_signatures_are_only_results_not_drops() {
    let unsigned = message(None);
    assert!(matches!(
        verifier().validate(reference_time(), &unsigned),
        Err(VerificationError::NoSignaturePresent)
    ));
    let only_key_id = OwnedHeaders::new().insert(Header {
        key: SIGNING_KEY_ID_HEADER,
        value: Some("test-ecdsa-v1"),
    });
    assert!(matches!(
        verifier().validate(reference_time(), &message(Some(only_key_id))),
        Err(VerificationError::NoSignaturePresent)
    ));
    let only_signature = OwnedHeaders::new().insert(Header {
        key: SIGNATURE_HEADER,
        value: Some(JVM_SIGNATURE),
    });
    assert!(matches!(
        verifier().validate(reference_time(), &message(Some(only_signature))),
        Err(VerificationError::NoKeyIdPresent)
    ));
    let oversized_key_id = "x".repeat(129);
    let headers = OwnedHeaders::new()
        .insert(Header {
            key: SIGNATURE_HEADER,
            value: Some(JVM_SIGNATURE),
        })
        .insert(Header {
            key: SIGNING_KEY_ID_HEADER,
            value: Some(oversized_key_id.as_bytes()),
        });
    assert!(matches!(
        verifier().validate(reference_time(), &message(Some(headers))),
        Err(VerificationError::Key(KeyError::UnknownKeyId { key_id })) if key_id == oversized_key_id
    ));
    let headers = OwnedHeaders::new()
        .insert(Header {
            key: SIGNATURE_HEADER,
            value: Some(JVM_SIGNATURE),
        })
        .insert(Header {
            key: SIGNING_KEY_ID_HEADER,
            value: Some("unknown"),
        });
    assert!(matches!(
        verifier().validate(reference_time(), &message(Some(headers))),
        Err(VerificationError::Key(KeyError::UnknownKeyId { key_id })) if key_id == "unknown"
    ));
    let headers = OwnedHeaders::new()
        .insert(Header {
            key: SIGNATURE_HEADER,
            value: Some("bad!!"),
        })
        .insert(Header {
            key: SIGNING_KEY_ID_HEADER,
            value: Some("test-ecdsa-v1"),
        });
    assert!(matches!(
        verifier().validate(reference_time(), &message(Some(headers))),
        Err(VerificationError::MalformedSignature {
            key_id: "test-ecdsa-v1"
        })
    ));
    let headers = OwnedHeaders::new()
        .insert(Header {
            key: SIGNATURE_HEADER,
            value: Some(JVM_SIGNATURE),
        })
        .insert(Header {
            key: SIGNING_KEY_ID_HEADER,
            value: Some(&[0xff]),
        });
    assert!(matches!(
        verifier().validate(reference_time(), &message(Some(headers))),
        Err(VerificationError::MalformedKeyId)
    ));
}

#[test]
fn absent_bytes_and_pem_wrapped_private_key() {
    let pem = format!("-----BEGIN PRIVATE KEY-----\n{PRIVATE_KEY}\n-----END PRIVATE KEY-----");
    let signer = RecordSigner::from_pkcs8_base64("test-ecdsa-v1", &pem).unwrap();
    let signed = signer
        .sign_record(FutureRecord::<[u8], [u8]>::to("topic").timestamp(TIMESTAMP))
        .unwrap();
    let headers = signed.headers.unwrap();
    let msg = OwnedMessage::new(
        None,
        None,
        "topic".into(),
        Timestamp::CreateTime(TIMESTAMP),
        0,
        0,
        Some(headers),
    );
    assert!(matches!(
        verifier().validate(reference_time(), &msg),
        Ok(ValidSignature {
            key_id: "test-ecdsa-v1"
        })
    ));
    let empty = strip_signing_headers(msg.headers());
    assert_eq!(empty.count(), 0);
    assert_eq!(STANDARD.decode(PRIVATE_KEY).unwrap().len(), 138);
}
